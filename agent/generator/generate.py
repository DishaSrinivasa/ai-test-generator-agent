"""Generate pytest test functions for an OpenAPI spec using Ollama + RAG."""
import ollama
from agent.rag.ingest import retrieve, COLLECTION_NAME
import chromadb

MODEL = "llama3.2"

SYSTEM_PROMPT = """\
You are an expert Python test engineer. Given context about a REST API endpoint, \
write a single pytest test function using httpx. Follow these rules:
- Use `httpx.Client` with `base_url` fixture, not raw URLs
- Import only from stdlib and httpx
- Test one happy-path scenario and one error scenario per endpoint
- Use descriptive function names like test_<method>_<resource>_<scenario>
- Return ONLY valid Python code, no markdown fences, no explanation
"""


def _all_endpoints(chroma_path: str) -> list[dict]:
    client = chromadb.PersistentClient(path=chroma_path)
    collection = client.get_or_create_collection(COLLECTION_NAME)
    results = collection.get(include=["documents", "metadatas"])
    return [
        {"text": doc, "method": meta["method"], "path": meta["path"]}
        for doc, meta in zip(results["documents"], results["metadatas"])
    ]


def generate_tests(chroma_path: str = "./chroma_db", base_url: str = "http://localhost:8000") -> str:
    """Generate a full pytest module as a string."""
    endpoints = _all_endpoints(chroma_path)
    if not endpoints:
        raise RuntimeError("No endpoints in ChromaDB — run ingest first.")

    test_functions: list[str] = []

    for ep in endpoints:
        context_chunks = retrieve(f"{ep['method']} {ep['path']}", n=2, chroma_path=chroma_path)
        context = "\n\n".join(context_chunks)

        prompt = (
            f"Base URL for the API under test: {base_url}\n\n"
            f"Endpoint context:\n{context}\n\n"
            f"Write pytest test functions for: {ep['method']} {ep['path']}"
        )

        response = ollama.chat(
            model=MODEL,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": prompt},
            ],
        )
        code = response["message"]["content"].strip()
        # Strip markdown fences if the model added them
        if code.startswith("```"):
            lines = code.splitlines()
            code = "\n".join(lines[1:-1] if lines[-1].strip() == "```" else lines[1:])
        test_functions.append(code)

    header = (
        "# Auto-generated by AI Test Generator Agent\n"
        "import httpx\nimport pytest\n\n"
        f'BASE_URL = "{base_url}"\n\n'
        "@pytest.fixture\ndef client():\n"
        "    with httpx.Client(base_url=BASE_URL) as c:\n"
        "        yield c\n\n"
    )
    return header + "\n\n".join(test_functions)
